// Normalizador inteligente para encontrar o tema correto a partir de qualquer string de banco
export function getBankTheme(bankIdOrName) {
  if (!bankIdOrName) return BANK_THEMES.nubank;
  const s = String(bankIdOrName).toLowerCase().trim();

  if (s.includes('nubank') || s === 'nu' || s === 'roxinho') return BANK_THEMES.nubank;
  if (s.includes('c6')) return BANK_THEMES.c6;
  if (s.includes('ita') || s.includes('itau')) return BANK_THEMES.itau;
  if (s.includes('bradesco')) return BANK_THEMES.bradesco;
  if (s.includes('brasil') || s === 'bb' || s.includes('banco do brasil')) return BANK_THEMES.bb;
  if (s.includes('santander')) return BANK_THEMES.santander;
  if (s.includes('inter')) return BANK_THEMES.inter;
  if (s.includes('caixa') || s === 'cef') return BANK_THEMES.caixa;
  if (s.includes('btg')) return BANK_THEMES.btg;
  if (s.includes('picpay')) return BANK_THEMES.picpay;
  if (s.includes('mercado') || s.includes('pago') || s === 'mp') return BANK_THEMES.mercadopago;
  if (s.includes('neon')) return BANK_THEMES.neon;
  if (s === 'xp' || s.includes('xp invest')) return BANK_THEMES.xp;
  if (s.includes('pag') || s.includes('seguro')) return BANK_THEMES.pagbank;
  if (s.includes('will')) return BANK_THEMES.will;
  if (s.includes('sicoob')) return BANK_THEMES.sicoob;
  if (s.includes('sicredi')) return BANK_THEMES.sicredi;
  if (s.includes('safra')) return BANK_THEMES.safra;

  // Se o ID direto existir
  if (BANK_THEMES[s]) return BANK_THEMES[s];

  return BANK_THEMES.default;
}

